"""Reproducible synthetic protocol check; not a spacecraft-performance benchmark."""

import argparse
from dataclasses import asdict
import json
from pathlib import Path
import platform

import numpy as np

from dataset import atomic_text, sha256
from retention.codec import Sample, decode_packet
from retention.evaluation import Event, evaluate_retention
from retention.recorder import Recorder, RecorderConfig


def make_scenario(seed=2026):
    generator = np.random.default_rng(seed)
    timestamps = np.arange(0, 1800, 5, dtype=np.int64) * 1_000_000
    values = generator.normal(0, 0.1, (len(timestamps), 6))
    # A spike, a sustained step, and a slow ramp exercise different evidence needs.
    values[47, 0] += 8
    values[137:143, 1] += 5
    values[260:281, 2] += np.linspace(0, 6, 21)
    source = [
        Sample(int(timestamp), tuple(row)) for timestamp, row in zip(timestamps, values)
    ]
    events = [
        Event("spike", 235_000_000, 235_000_000, (0,)),
        Event("step", 685_000_000, 715_000_000, (1,)),
        Event("ramp", 1_300_000_000, 1_405_000_000, (2,)),
    ]
    return source, events


def run_demo(output: Path, latex: Path | None = None):
    config = RecorderConfig(
        epoch_us=600_000_000,
        budget_bytes=1024,
        threshold=2,
        pre_trigger_samples=3,
        post_trigger_samples=3,
    )
    source, events = make_scenario()
    output.mkdir(parents=True, exist_ok=True)
    report = dict(
        kind="synthetic_protocol_smoke_test",
        seed=2026,
        config=asdict(config),
        python=platform.python_version(),
        numpy=np.__version__,
        scripts={
            path.name: sha256(path)
            for path in [
                Path(__file__),
                *sorted((Path(__file__).parent / "retention").glob("*.py")),
            ]
        },
        policies={},
    )
    for policy in Recorder.POLICIES:
        recorder = Recorder(policy, config)
        packets = []
        previous = None
        for sample in source:
            # A causal first-difference capture trigger. It has no access to labels.
            score = (
                0
                if previous is None
                else max(abs(a - b) for a, b in zip(sample.values, previous.values))
            )
            packet = recorder.observe(sample, score)
            if packet is not None:
                packets.append(packet)
            previous = sample
        packets.append(recorder.finish())
        decoded = []
        for index, packet in enumerate(packets):
            encoded = packet.encode()
            (output / f"{policy}-{index:03d}.taer").write_bytes(encoded)
            decoded.append(decode_packet(encoded))
        report["policies"][policy] = evaluate_retention(decoded, source, events)
    atomic_text(
        output / "report.json", json.dumps(report, indent=2, allow_nan=False) + "\n"
    )
    if latex:
        rows = [
            "% Generated by python/run_retention_demo.py; synthetic checks only.",
            r"\begin{tabular}{lrrrr}",
            r"\toprule",
            r"Policy & Bytes & Raw records & Raw event coverage & Receiver evidence \\",
            r"\midrule",
        ]
        for policy, metrics in report["policies"].items():
            rows.append(
                f"{policy.capitalize()} & {metrics['serialized_bytes']} & {metrics['retained_raw_samples']} & "
                f"{metrics['events_with_raw_samples']}/3 & {metrics['events_with_receiver_evidence']}/3 "
                + r"\\"
            )
        rows.extend([r"\bottomrule", r"\end{tabular}"])
        atomic_text(latex, "\n".join(rows) + "\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=Path("data/results/retention-smoke")
    )
    parser.add_argument("--latex", type=Path)
    args = parser.parse_args()
    report = run_demo(args.output, args.latex)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
